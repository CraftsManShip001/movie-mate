/** 1번 화면에서 극장을 나누는 지역 (순서 고정). 주소의 시·도로 정한다. */
export const REGIONS = ["서울", "경기·인천", "충청·대전", "전라·광주", "경북·대구", "부산·울산·경남", "강원", "제주"] as const;

export type Region = (typeof REGIONS)[number];

const PROVINCE_REGION: [string, Region][] = [
  ["서울", "서울"],
  ["경기", "경기·인천"],
  ["인천", "경기·인천"],
  ["대전", "충청·대전"],
  ["세종", "충청·대전"],
  ["충청", "충청·대전"],
  ["충북", "충청·대전"],
  ["충남", "충청·대전"],
  ["광주", "전라·광주"],
  ["전라", "전라·광주"],
  ["전북", "전라·광주"],
  ["전남", "전라·광주"],
  ["대구", "경북·대구"],
  ["경상북", "경북·대구"],
  ["경북", "경북·대구"],
  ["부산", "부산·울산·경남"],
  ["울산", "부산·울산·경남"],
  ["경상남", "부산·울산·경남"],
  ["경남", "부산·울산·경남"],
  ["강원", "강원"],
  ["제주", "제주"],
];

/** 주소 첫 낱말(시·도)로 지역을 고른다. "경기 광명시", "경기도 광명시" 모두 "경기·인천"이다. */
export function regionOf(address: string): Region | null {
  const province = address.trim().split(/\s+/)[0] ?? "";
  return PROVINCE_REGION.find(([prefix]) => province.startsWith(prefix))?.[1] ?? null;
}
